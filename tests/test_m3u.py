"""Bugs 10-13: album-m3u generated-vs-hand-made, header, encoding, multi-disc, stale."""

import os


def touch(path, data=b"x"):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return path


def lines(path):
    return path.read_bytes().decode("utf-8", "surrogateescape").splitlines()


def test_detection(common, tmp_path):
    album = tmp_path / "Album"
    touch(album / "1. a.flac")
    touch(album / "2. b.flac")
    marked = album / "whatever.m3u8"
    marked.write_text("#EXTM3U\n# generated by album-m3u\n1. a.flac\n", encoding="utf-8")
    legacy = album / "Album.m3u"
    legacy.write_text("1. a.flac\n2. b.flac\n", encoding="utf-8")
    assert common.is_generated_playlist(marked)
    assert common.is_generated_playlist(legacy)

    # hand-made: other name / reordered / comments / paths / other folder's files
    for name, text in [
        ("mix.m3u", "1. a.flac\n2. b.flac\n"),
        ("Album.m3u8", "1. a.flac\n2. b.flac\n"),
    ]:
        p = album / name
        p.write_text(text, encoding="utf-8")
        assert not common.is_generated_playlist(p), name
    for text in ["2. b.flac\n1. a.flac\n", "#EXTM3U\n1. a.flac\n", "../Other/1. x.flac\n", "1. a.flac\nmissing.flac\n",
                 "1. a.flac\n1. a.flac\n", "notes.txt\n"]:
        legacy.write_text(text, encoding="utf-8")
        assert not common.is_generated_playlist(legacy), text


def test_rebuild_keeps_handmade_and_writes_header(m3u, common, tmp_path):
    album = tmp_path / "Artist" / "Album"
    touch(album / "1. a.flac")
    touch(album / "2. b.flac")
    (album / "Album.m3u").write_text("1. a.flac\n2. b.flac\n", encoding="utf-8")  # legacy generated
    mine = album / "my order.m3u"
    mine.write_text("2. b.flac\n1. a.flac\n", encoding="utf-8")
    other = tmp_path / "road trip.m3u8"
    other.write_text("#EXTM3U\nArtist/Album/1. a.flac\n", encoding="utf-8")
    assert m3u.main(["rebuild", "--root", str(tmp_path)]) == 0
    assert mine.read_text(encoding="utf-8") == "2. b.flac\n1. a.flac\n"
    assert other.exists()
    assert lines(album / "Album.m3u") == ["#EXTM3U", common.GENERATED_MARKER, "1. a.flac", "2. b.flac"]


def test_rebuild_dry_run_deletes_nothing(m3u, tmp_path):
    album = tmp_path / "Artist" / "Album"
    touch(album / "1. a.flac")
    legacy = album / "Album.m3u"
    legacy.write_text("1. a.flac\n", encoding="utf-8")
    m3u.main(["rebuild", "--root", str(tmp_path), "--dry-run"])
    assert legacy.read_text(encoding="utf-8") == "1. a.flac\n"


def test_handmade_with_album_name_never_overwritten(m3u, tmp_path):
    album = tmp_path / "Artist" / "Album"
    touch(album / "1. a.flac")
    touch(album / "2. b.flac")
    mine = album / "Album.m3u"
    mine.write_text("#EXTM3U\n#EXTINF:1,b\n2. b.flac\n", encoding="utf-8")
    m3u.main(["rebuild", "--root", str(tmp_path)])
    m3u.main(["update", "--root", str(tmp_path)])
    assert mine.read_text(encoding="utf-8") == "#EXTM3U\n#EXTINF:1,b\n2. b.flac\n"


def test_multi_disc_one_playlist(m3u, common, tmp_path):
    album = tmp_path / "Artist" / "Box"
    touch(album / "CD2" / "1. c.flac")
    touch(album / "CD1" / "1. a.flac")
    touch(album / "CD1" / "2. b.flac")
    touch(album / "CD10" / "1. z.flac")
    (album / "CD1" / "CD1.m3u").write_text("1. a.flac\n2. b.flac\n", encoding="utf-8")  # old per-disc
    m3u.main(["update", "--root", str(tmp_path)])
    assert not (album / "CD1" / "CD1.m3u").exists()
    assert lines(album / "Box.m3u")[2:] == ["CD1/1. a.flac", "CD1/2. b.flac", "CD2/1. c.flac", "CD10/1. z.flac"]
    assert not (album / "CD2" / "CD2.m3u").exists()


def test_update_replaces_stale_generated(m3u, common, tmp_path):
    album = tmp_path / "Artist" / "Album"
    touch(album / "1. a.flac")
    m3u.main(["update", "--root", str(tmp_path)])
    playlist = album / "Album.m3u"
    first = playlist.read_bytes()
    m3u.main(["update", "--root", str(tmp_path)])
    assert playlist.read_bytes() == first  # up to date: untouched
    (album / "1. a.flac").rename(album / "1. Renamed.flac")
    m3u.main(["update", "--root", str(tmp_path)])
    assert lines(playlist)[2:] == ["1. Renamed.flac"]


def test_update_after_folder_rename_removes_old_generated(m3u, tmp_path):
    album = tmp_path / "Artist" / "Old Name"
    touch(album / "1. a.flac")
    m3u.main(["update", "--root", str(tmp_path)])
    new = album.rename(tmp_path / "Artist" / "New Name")
    m3u.main(["update", "--root", str(tmp_path)])
    assert sorted(p.name for p in new.glob("*.m3u")) == ["New Name.m3u"]


def test_stale_carried_legacy_playlist_is_reported_not_deleted(m3u, tmp_path, capsys):
    album = tmp_path / "Artist" / "[1999]  New [1999]"
    touch(album / "1. Song.flac")
    old = album / "Artist - Old.m3u"  # what old discogs-tag carried along
    old.write_text("01 - song.flac\n", encoding="utf-8")
    m3u.main(["rebuild", "--root", str(tmp_path)])
    assert old.exists()
    assert "review it" in capsys.readouterr().out


def test_non_ascii_and_hash_and_undecodable_names(m3u, tmp_path):
    album = tmp_path / "Artist" / "Album"
    touch(album / "1. ひこうき雲.flac")
    touch(album / "#2 Crush.flac")
    raw = os.fsencode(str(album)) + b"/3. caf\xe9.flac"  # Latin-1 byte, not valid UTF-8
    with open(raw, "wb") as handle:
        handle.write(b"x")
    m3u.main(["rebuild", "--root", str(tmp_path)])
    data = (album / "Album.m3u").read_bytes()
    assert "1. ひこうき雲.flac".encode() in data
    assert b"\n./#2 Crush.flac\n" in data  # not mistaken for a comment
    assert b"3. caf\xe9.flac" in data  # exact on-disk bytes
